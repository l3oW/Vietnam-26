export function normalizeFruitName(value){return String(value??'').normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLocaleLowerCase('de-DE').replace(/[^\p{L}\p{N}]+/gu,' ').trim();}
export function tripMonths(startDate){const start=new Date(startDate+'T12:00:00Z');if(Number.isNaN(start.getTime()))return [];return [...new Set(Array.from({length:14},(_,i)=>{const day=new Date(start);day.setUTCDate(day.getUTCDate()+i);return day.getUTCMonth()+1;}))];}
export function matchingFruit(name){const normalized=normalizeFruitName(name);return FRUIT_CATALOG.find(f=>[f.name,f.local,...f.aliases].some(alias=>normalizeFruitName(alias)===normalized));}
export function fruitSelection(startDate,custom=[],checks=[],userId=''){
const months=tripMonths(startDate);
const curated=FRUIT_CATALOG.filter(f=>f.months.some(m=>months.includes(m))).map(f=>({...f,custom:false,canDelete:false,availability:f.peak.some(m=>months.includes(m))?'Saison':f.regional?'Regional erhältlich':'Ganzjährig'}));
const own=custom.map(f=>({id:f.id,name:f.name,local:f.local_name,description:f.notes||'Von unserer Reisecrew ergänzt.',color:'#b47a55',taste:'unser eigener Fund',custom:true,canDelete:f.author_id===userId,availability:'Eigener Fund'}));
const all=[...curated,...own].map(f=>({...f,tasted:checks.includes('fruit-'+f.id)}));
return {fruits:all,fruitSummary:{total:all.length,tasted:all.filter(f=>f.tasted).length,custom:own.length,hidden:FRUIT_CATALOG.length-curated.length,months},fruitSources:FRUIT_SOURCES};
}
